#!/usr/bin/env bash
# Writes <repo>/THIRD-PARTY-NOTICES.txt - the license notices of the third-party code that ships inside the services.
# MIT, BSD and Apache-2.0 ask for their notice to travel with a binary and MPL-2.0 for a pointer to the source, so both
# installers put the file beside LICENSE (apps/OpcHub/setup) and web/opc/scripts/setup.sh serves it with the site, next
# to the web bundle's own list (ng build's 3rdpartylicenses.txt).
#
# The output is checked in - the Windows packaging run has the deps' install tree, not their sources - so re-run this
# after bumping a GIT_TAG in the CMakeLists.txt beside it.  Versions are read from that file; the texts come verbatim
# from the sources the -repos build fetched and, for what the system or vcpkg provides, from Debian's copyright files.
set -euo pipefail

usage(){ cat <<'USAGE'
usage: third-party-notices.sh [options]
  --repos-dir <dir>  the -repos build's ExternalProject root   default: $REPO_DIR/build/<relWithDebInfo|release|debug>/repos
  --out <file>       default: <repo>/THIRD-PARTY-NOTICES.txt
  -h, --help
USAGE
}
die(){ echo "third-party-notices.sh: $*" >&2; exit 1; }

scriptDir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
repo=$(cd "$scriptDir/.." && pwd)
cmake=$scriptDir/CMakeLists.txt
libs=${REPO_DIR:-$HOME/code/libs}
reposDir=; out=$repo/THIRD-PARTY-NOTICES.txt
while [ $# -gt 0 ]; do
	case "$1" in
		--repos-dir) reposDir=${2:?}; shift 2;; --repos-dir=*) reposDir=${1#*=}; shift;;
		--out) out=${2:?}; shift 2;;            --out=*) out=${1#*=}; shift;;
		-h|--help) usage; exit 0;;
		*) usage >&2; die "unknown option '$1'";;
	esac
done
if [ -z "$reposDir" ]; then
	for t in relWithDebInfo release debug; do
		if [ -d "$libs/build/$t/repos" ]; then reposDir=$libs/build/$t/repos; break; fi
	done
fi
[ -d "$reposDir" ] || die "no fetched sources under $libs/build - build a -repos preset first, or pass --repos-dir"

tag(){ #ExternalProject name -> its GIT_TAG, a ${var} resolved through its set()
	local t
	t=$(awk -v p="$1" '
		/ExternalProject_Add\(/ { cur=$0; sub(/.*ExternalProject_Add\([ \t]*/, "", cur); if( cur ~ /^[ \t\r]*$/ ){ getline cur }; gsub(/[ \t\r]/, "", cur) }
		cur==p && $1=="GIT_TAG" { gsub(/"/, "", $2); print $2; exit }' "$cmake")
	if [[ $t == '${'*'}' ]]; then
		t=${t#'${'}; t=${t%'}'}
		t=$(awk -v v="$t" '$1=="set(" && $2==v { print $3; exit }' "$cmake")
	fi
	[ -n "$t" ] || die "no GIT_TAG for '$1' in $cmake"
	echo "$t"
}
rule=$(printf '=%.0s' {1..100})
section(){ #title url license [note]
	printf '\n%s\n%s\n%s\nLicense: %s\n' "$rule" "$1" "$2" "$3"
	[ -z "${4:-}" ] || printf '%s\n' "$4"
	printf '%s\n\n' "$rule"
}
text(){ [ -f "$1" ] || die "$1 is missing"; sed 's/[ \t\r]*$//' "$1"; } #verbatim, bar the trailing whitespace
debian(){ #the first of these packages that has a copyright file
	local p
	for p in "$@"; do
		if [ -f "/usr/share/doc/$p/copyright" ]; then text "/usr/share/doc/$p/copyright"; return; fi
	done
	die "no /usr/share/doc/<$*>/copyright"
}

#resolved up front:  a die inside the $(...) of a printf argument would not stop the script
fmtTag=$(tag fmt); spdlogTag=$(tag spdlog); abslTag=$(tag absl); rymlTag=$(tag ryml); jsonnetTag=$(tag jsonnet)
protobufTag=$(tag protobuf); open62541Tag=$(tag open62541); nodesetTag=$(tag open62541-nodeset-loader)
zlibTag=$(tag zlib); libxml2Tag=$(tag LibXml2)
boostLicense=$(ls -d "$libs"/boost_*/LICENSE_1_0.txt 2>/dev/null | sort -V | tail -1)
[ -n "$boostLicense" ] || die "no $libs/boost_*/LICENSE_1_0.txt"
icuPackage=$(cd /usr/share/doc && ls -d libicu[0-9]* 2>/dev/null | sort -V | tail -1)
[ -n "$icuPackage" ] || die "no /usr/share/doc/libicu<N>"
ours="https://github.com/Jde-cpp/opc-hub (build/CMakeLists.txt)"

tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT
{
	cat <<HEADER
OPC Hub - third-party notices

OPC Hub itself is MIT licensed (LICENSE, beside this file).  Its services - Jde.Opc.Hub, Jde.Opc.Server and the
libraries installed with them - contain or are shipped with the third-party software below, each under its own
license.  The web site's bundle has a list of its own, 3rdpartylicenses.txt, served beside index.html.

Each component is built from the unmodified upstream tag named here unless its entry says otherwise; where it says
otherwise, the change is the patch step in $ours.
Test-only dependencies (GoogleTest) are not shipped and are not listed.

Generated by build/third-party-notices.sh - edit that, not this file.
HEADER

	section "fmt $fmtTag" https://github.com/fmtlib/fmt MIT
	text "$reposDir/fmt/src/fmt/LICENSE"
	section "spdlog $spdlogTag" https://github.com/gabime/spdlog MIT
	text "$reposDir/spdlog/src/spdlog/LICENSE"
	section "Abseil $abslTag" https://github.com/abseil/abseil-cpp Apache-2.0
	text "$reposDir/absl/src/absl/LICENSE"
	section "Protocol Buffers $protobufTag" https://github.com/protocolbuffers/protobuf BSD-3-Clause
	text "$reposDir/protobuf/src/protobuf/LICENSE"
	section "utf8_range (bundled in Protocol Buffers $protobufTag)" https://github.com/protocolbuffers/protobuf/tree/main/third_party/utf8_range MIT
	text "$reposDir/protobuf/src/protobuf/third_party/utf8_range/LICENSE"

	ryml=$reposDir/ryml/src/ryml
	section "rapidyaml $rymlTag" https://github.com/biojppm/rapidyaml MIT \
		"Windows builds patch ext/c4core/cmake/c4Project.cmake and src/c4/yml/common.hpp (platform tag, alloca)."
	text "$ryml/LICENSE.txt"
	section "c4core (bundled in rapidyaml $rymlTag)" https://github.com/biojppm/c4core MIT
	text "$ryml/ext/c4core/LICENSE.txt"
	section "fast_float (bundled in c4core)" https://github.com/fastfloat/fast_float "MIT (offered as Apache-2.0 OR BSL-1.0 OR MIT)"
	text "$ryml/ext/c4core/src/c4/ext/fast_float/LICENSE-MIT"
	section "debugbreak (bundled in c4core)" https://github.com/scottt/debugbreak BSD-2-Clause
	text "$ryml/ext/c4core/src/c4/ext/debugbreak/COPYING"

	jsonnet=$reposDir/jsonnet/src/jsonnet
	section "Jsonnet $jsonnetTag" https://github.com/google/jsonnet Apache-2.0 \
		"Modified: CMakeLists.txt (the ryml find_package call) and core/vm.cpp (an added #include <ryml_std.hpp>; on Windows, RuntimeError's constructor)."
	text "$jsonnet/LICENSE"
	section "JSON for Modern C++ (bundled in Jsonnet $jsonnetTag)" https://github.com/nlohmann/json MIT
	text "$jsonnet/third_party/json/LICENSE"
	section "MD5 (bundled in Jsonnet $jsonnetTag)" http://www.zedwood.com/article/cpp-md5-function "RSA Data Security, Inc. MD5 Message-Digest Algorithm notice"
	text "$jsonnet/third_party/md5/LICENSE"

	open62541=$reposDir/open62541/src/open62541
	section "open62541 $open62541Tag" https://github.com/open62541/open62541 MPL-2.0 \
		"Source code: the URL above, at the tag above - built unmodified."
	text "$open62541/LICENSE"
	printf '\nopen62541 bundles these libraries (its deps/README.md):\n\n'
	sed -n '/^| Library/,$p' "$open62541/deps/README.md" | sed 's/[ \t\r]*$//'
	section "open62541-nodeset-loader $nodesetTag" https://github.com/open62541/open62541-nodeset-loader MPL-2.0 \
		"Source code: the URL above, at the commit above.  Modified: CMakeLists.txt only (-Werror, a stale install() line, an added config-file install rule)."
	text "$reposDir/nodeset-loader/src/open62541-nodeset-loader/LICENSE"

	section "Boost" https://www.boost.org BSL-1.0
	text "$boostLicense"
	section "SQLite" https://www.sqlite.org/copyright.html "Public domain" \
		"Windows: vcpkg's sqlite3.dll, at the version vcpkg.json's builtin-baseline resolves (named in its \$comment)."
	echo "SQLite is in the public domain and asks for no notice; it is listed for completeness."
	#Not "linked statically on Linux":  both exes import libssl.so.3/libcrypto.so.3 and the package Depends on libssl3t64
	#(reviews/m4-closing.md #22) - nothing of OpenSSL is inside the Linux binaries.
	section "OpenSSL" https://www.openssl.org Apache-2.0 \
		"Windows: vcpkg's DLLs, shipped, at the version vcpkg.json's builtin-baseline resolves (named in its \$comment).  Linux: the system's libssl3t64, a package dependency - nothing of it is inside the binaries.  The Apache License 2.0 text is reproduced under Abseil above."
	debian libssl3t64 libssl3
	section "libxml2 (Windows: $libxml2Tag; Linux: the build machine's libxml2.so, bundled)" https://gitlab.gnome.org/GNOME/libxml2 MIT
	debian libxml2-16 libxml2
	section "zlib $zlibTag (Windows only)" https://github.com/madler/zlib Zlib
	debian zlib1g
	section "ICU (Linux only: libicuuc and libicudata, bundled for libxml2)" https://icu.unicode.org "Unicode-3.0 and others"
	debian "$icuPackage"
	section "LLVM libc++ and libc++abi (Linux only, bundled)" https://libcxx.llvm.org "Apache-2.0 WITH LLVM-exception" \
		"The Apache License 2.0 text is reproduced under Abseil above."
	debian libc++1 "$(cd /usr/share/doc && ls -d libc++1-[0-9]* 2>/dev/null | sort -V | tail -1)"
	#the release runner builds libbacktrace static-only (.github/docker/Dockerfile) and the Linux presets link it for
	#Boost.Stacktrace (-lbacktrace), so its object code is inside both exes - BSD-3-Clause, whose clause (2) asks for this
	#notice (reviews/m4-closing.md #22).  Windows uses WinDbg for stack traces, not this.
	section "libbacktrace (Linux only, statically linked into Jde.Opc.Hub and Jde.Opc.Server)" https://github.com/ianlancetaylor/libbacktrace BSD-3-Clause
	debian libbacktrace0 libbacktrace-dev
	#libJde's io_uring (.github/docker/Dockerfile):  the .deb depends on liburing2, but the per-user tarball carries
	#liburing.so.2, since nothing installs a tarball's dependencies (apps/OpcHub/setup/linux/build-deb.sh; reviews/install-issues.md #59)
	section "liburing (Linux only: the .deb depends on liburing2; the per-user tarball bundles liburing.so.2)" https://github.com/axboe/liburing "MIT (offered as LGPL-2.1 OR MIT)"
	debian liburing2
} > "$tmp"
mv "$tmp" "$out"; trap - EXIT
chmod 644 "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
